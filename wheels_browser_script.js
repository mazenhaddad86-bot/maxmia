async function pollVideoJob(jobSetId, label) {
  for (let i = 0; i < 180; i++) {
    await sleep(8000);
    try {
      const d = await api('GET', '/jobs/' + jobSetId);
      const url = extractUrl(d);
      if (url) return url;
      const status = d.status || d.job_set_status;
      if (status === 'failed' || status === 'error') throw new Error(`Video failed: ${jobSetId}`);
      // Also check jobs list every 3rd poll
      if (i % 3 === 0) {
        const list = await api('GET', '/jobs?page=1&per_page=50');
        const jobs = list.jobs || list.job_sets || [];
        const found = jobs.find(j => (j.job_set_id || j.id) === jobSetId);
        if (found) {
          const u = extractUrl(found);
          if (u) return u;
        }
      }
      if (i % 6 === 0) console.log(`  ⏳ ${label} vid [${status||'?'}] ${i*8}s`);
    } catch(e) {
      if (!e.message.includes('404')) throw e;
    }
  }
  throw new Error(`Timeout video: ${jobSetId}`);
}

