// BATCH RUNNER
// ===================================
async function runBatch(items, fn, n, pauseMs) {
  for (let i = 0; i < items.length; i += n) {
    const batch = items.slice(i, i + n);
    const batchNum = Math.floor(i/n) + 1;
    const total = Math.ceil(items.length/n);
    // Skip pause if all in batch already cached
    const fresh = JSON.parse(localStorage.getItem('wheels_progress') || '{}');
    const allCached = batch.every(x => {
      const id = x.id || x.clip?.id;
      return fresh.images?.[id]?.url || fresh.videos?.[id]?.url;
    });
    console.log(`\n%c📦 Batch ${batchNum}/${total}: [${batch.map(x=>x.id).join(', ')}]${allCached?' (cached)':''}`, 'color:orange;font-weight:bold');
    const settled = await Promise.allSettled(batch.map((item, j) => fn(item, i+j)));
    for (let j = 0; j < settled.length; j++) {
      if (settled[j].status === 'rejected') {
        console.error(`%c❌ ${batch[j].id} FAILED: ${settled[j].reason?.message}`, 'color:red');
      }
    }
    if (!allCached && i + n < items.length) await sleep(pauseMs);
  }
}

