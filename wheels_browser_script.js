// ===================================
async function pollImageJob(jobSetId, label) {
  for (let i = 0; i < 180; i++) {
    await sleep(6000);
    // Try direct endpoint
    try {
      const d = await api('GET', '/jobs/' + jobSetId);
      const url = extractUrl(d);
      if (url) return { url, d };
      const status = d.status || d.job_set_status || d.jobs?.[0]?.status;
      if (status === 'failed' || status === 'error') throw new Error(`Job failed: ${jobSetId}`);
    } catch(e) {
      if (!e.message.includes('404') && !e.message.includes('405')) throw e;
    }
    // Fallback: jobs list
    try {
      const list = await api('GET', '/jobs?page=1&per_page=50');
      const jobs = list.jobs || list.job_sets || [];
      const found = jobs.find(j => (j.job_set_id || j.id) === jobSetId);
      if (found) {
        const url = extractUrl(found);
        if (url) return { url, d: found };
        const status = found.status || found.job_set_status;
        if (status === 'failed' || status === 'error') throw new Error(`Job failed: ${jobSetId}`);
      }
    } catch(e2) {}
    if (i % 10 === 0) console.log(`  ⏳ ${label} img ${i*6}s...`);
  }
  throw new Error(`Timeout image: ${jobSetId}`);
}

async function generateImage(clip) {
  const fresh = JSON.parse(localStorage.getItem('wheels_progress') || '{}');
  if (fresh.images?.[clip.id]?.url) {
    console.log(`%c✅ ${clip.id} image cached`, 'color:green');
    return fresh.images[clip.id];
  }

  const d = await api('POST', '/jobs/nano-banana-pro', {
    use_unlim: true,
    params: {
      width: 1376, height: 768,
      aspect_ratio: '16:9',
      resolution: '1k',
      batch_size: 1,
      prompt: clip.prompt,
      input_images: [REF_IMG],
    }
  });

  const cost = d.job_sets?.[0]?.cost ?? d.cost ?? null;
  if (cost !== null && cost > 0) throw new Error(`💸 COST DETECTED ${cost} credits! ABORTING!`);

  // Check sync response
  const directUrl = extractUrl(d);
  if (directUrl) {
    const imgId = d.jobs?.[0]?.id || d.id || clip.id;
    const data = { id: imgId, url: directUrl, jobSetId: imgId };
    saveClip('images', clip.id, data);
    console.log(`%c✅ ${clip.id} image done (sync)`, 'color:green');
    return data;
  }

  const jobSetId = d.job_sets?.[0]?.id || d.job_set_id || d.jobs?.[0]?.job_set_id;
  if (!jobSetId) throw new Error(`No jobSetId: ${JSON.stringify(d).slice(0,200)}`);

  saveClip('images', clip.id, { jobSetId });
  console.log(`%c🖼️ ${clip.id} submitted [${jobSetId.slice(0,8)}]`, 'color:#4af');

  const { url, d: result } = await pollImageJob(jobSetId, clip.id);
  const imgId = result.jobs?.[0]?.id || jobSetId;

  const data = { id: imgId, url, jobSetId };
  saveClip('images', clip.id, data);
  console.log(`%c✅ ${clip.id} image done`, 'color:green');
  return data;
}

